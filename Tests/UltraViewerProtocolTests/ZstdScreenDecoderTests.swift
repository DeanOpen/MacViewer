import Foundation
import Testing
@testable import UltraViewerProtocol

private let compressedScreenFixture = Data([
    0x28, 0xb5, 0x2f, 0xfd, 0x00, 0x58, 0x0d, 0x01, 0x00, 0xc8, 0x4d, 0x61,
    0x63, 0x56, 0x69, 0x65, 0x77, 0x65, 0x72, 0x20, 0x73, 0x63, 0x72, 0x65,
    0x65, 0x6e, 0x20, 0x66, 0x69, 0x78, 0x74, 0x75, 0x72, 0x65, 0x0a, 0x01,
    0x00, 0xa1, 0x86, 0xfd, 0x39, 0x06,
]) // Independent zstd CLI -3 --no-check output, not generated by this decoder.

@Test func zstdScreenFixtureAtEveryFragmentBoundary() throws {
    let expected = Data(String(repeating: "MacViewer screen fixture\n", count: 100).utf8)
    for split in 0...compressedScreenFixture.count {
        let decoder = try ZstdScreenDecoder()
        var decoded = try decoder.append(Data(compressedScreenFixture.prefix(split)))
        decoded += try decoder.append(Data(compressedScreenFixture.dropFirst(split)))
        try decoder.finish()
        #expect(decoded == expected)
        #expect(!decoder.hasIncompleteFrame)
    }
}

@Test func zstdRejectsTruncationAndLimitsExpansionAcrossChunks() throws {
    let truncated = try ZstdScreenDecoder()
    _ = try truncated.append(Data(compressedScreenFixture.dropLast()))
    #expect(throws: ZstdScreenDecoder.Error.incompleteFrame) { try truncated.finish() }
    let bounded = try ZstdScreenDecoder(maximumOutputBytes: 100)
    #expect(throws: ZstdScreenDecoder.Error.outputLimitExceeded) {
        for byte in compressedScreenFixture { _ = try bounded.append(Data([byte])) }
    }
    #expect(throws: ZstdScreenDecoder.Error.resetRequired) { try bounded.append(Data([1])) }
    try bounded.reset()
    // A manually encoded standard raw block: one three-byte frame containing ABC.
    let rawFrame = Data([0x28, 0xb5, 0x2f, 0xfd, 0x20, 0x03, 0x19, 0, 0, 65, 66, 67])
    #expect(try bounded.append(rawFrame) == Data("ABC".utf8))
    try bounded.finish()
}

@Test func zstdConcatenatedFramesAndCorruption() throws {
    let decoder = try ZstdScreenDecoder(maximumOutputBytes: 6000)
    #expect(try decoder.append(compressedScreenFixture + compressedScreenFixture).count == 5000)
    try decoder.finish()
    try decoder.reset()
    #expect(throws: (any Error).self) { try decoder.append(Data("invalid compressed frame".utf8)) }
}

@Test func trainedScreenDictionarySurvivesMissionReset() throws {
    // Independent zstd CLI -3 -D 8bit.dat output, with dictionary ID 3da0bd10.
    let compressed = try #require(Data(base64Encoded:
        "KLUv/QdYEL2gPS0BAOhNYWNWaWV3ZXIgZGljdGlvbmFyeSBmaXh0dXJlCgEA0Qz4ygnbOEGJ"))
    let expected = Data(String(repeating: "MacViewer dictionary fixture\n", count: 100).utf8)
    let missingDictionary = try ZstdScreenDecoder()
    #expect(throws: ZstdScreenDecoder.Error.invalidData("Dictionary mismatch")) {
        try missingDictionary.append(compressed)
    }
    let decoder = try ZstdScreenDecoder(dictionary: UltraViewerScreenDictionary.load())
    for _ in 0..<2 {
        var result = Data()
        for byte in compressed { result += try decoder.append(Data([byte])) }
        try decoder.finish()
        #expect(result == expected)
        try decoder.reset()
    }
}
